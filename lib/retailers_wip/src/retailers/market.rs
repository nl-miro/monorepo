//! Typed countries and regions represented in the retailer inventory.

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Market {
    Country(Country),
    Region(Region),
}

impl Market {
    /// Returns the country or region's uppercase inventory code.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Country(country) => country.as_str(),
            Self::Region(region) => region.as_str(),
        }
    }

    /// Parses a country or region without treating regional codes as countries.
    pub fn from_code(code: &str) -> Option<Self> {
        Country::from_code(code)
            .map(Self::Country)
            .or_else(|| Region::from_code(code).map(Self::Region))
    }
}

