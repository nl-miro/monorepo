//! GraphQL language codes used in [the retailer inventory](../../../../docs/retailer.md).

/// A GraphQL language, independent of the locale tag and selected market.
#[allow(non_camel_case_types)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Language {
    AR,
    BG,
    CS,
    DA,
    DE,
    EL,
    EN,
    ES,
    ET,
    FI,
    FR,
    HI,
    HR,
    HU,
    ID,
    IT,
    JA,
    KO,
    LV,
    NL,
    PL,
    PT,
    RO,
    RU,
    SK,
    SL,
    SV,
    TH,
    TR,
    VI,
    ZH_TW,
}

impl Language {
    /// Returns the exact GraphQL language code.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::AR => "AR",
            Self::BG => "BG",
            Self::CS => "CS",
            Self::DA => "DA",
            Self::DE => "DE",
            Self::EL => "EL",
            Self::EN => "EN",
            Self::ES => "ES",
            Self::ET => "ET",
            Self::FI => "FI",
            Self::FR => "FR",
            Self::HI => "HI",
            Self::HR => "HR",
            Self::HU => "HU",
            Self::ID => "ID",
            Self::IT => "IT",
            Self::JA => "JA",
            Self::KO => "KO",
            Self::LV => "LV",
            Self::NL => "NL",
            Self::PL => "PL",
            Self::PT => "PT",
            Self::RO => "RO",
            Self::RU => "RU",
            Self::SK => "SK",
            Self::SL => "SL",
            Self::SV => "SV",
            Self::TH => "TH",
            Self::TR => "TR",
            Self::VI => "VI",
            Self::ZH_TW => "ZH_TW",
        }
    }

    /// Parses an exact uppercase inventory code; unknown codes return `None`.
    pub fn from_code(code: &str) -> Option<Self> {
        match code {
            "AR" => Some(Self::AR),
            "BG" => Some(Self::BG),
            "CS" => Some(Self::CS),
            "DA" => Some(Self::DA),
            "DE" => Some(Self::DE),
            "EL" => Some(Self::EL),
            "EN" => Some(Self::EN),
            "ES" => Some(Self::ES),
            "ET" => Some(Self::ET),
            "FI" => Some(Self::FI),
            "FR" => Some(Self::FR),
            "HI" => Some(Self::HI),
            "HR" => Some(Self::HR),
            "HU" => Some(Self::HU),
            "ID" => Some(Self::ID),
            "IT" => Some(Self::IT),
            "JA" => Some(Self::JA),
            "KO" => Some(Self::KO),
            "LV" => Some(Self::LV),
            "NL" => Some(Self::NL),
            "PL" => Some(Self::PL),
            "PT" => Some(Self::PT),
            "RO" => Some(Self::RO),
            "RU" => Some(Self::RU),
            "SK" => Some(Self::SK),
            "SL" => Some(Self::SL),
            "SV" => Some(Self::SV),
            "TH" => Some(Self::TH),
            "TR" => Some(Self::TR),
            "VI" => Some(Self::VI),
            "ZH_TW" => Some(Self::ZH_TW),
            _ => None,
        }
    }
}
